# Keyword arguments the stock SDK does not have. They are passed when present
# and dropped -- once, with a warning -- if this build rejects them, so the
# script still runs against an unpatched sipsimple.core, just less faithfully.
OPTIONAL_KWARGS = {
    'raw_sdp': 'relayed SDP will be regenerated by the pjsip SDP negotiator',
    'call_id': 'the outgoing Call-ID will be the one pjsip generates',
}
_unsupported_kwargs = set()


def send(method, *args, **kwargs):
    """Call an Invitation.send_* method, dropping any of OPTIONAL_KWARGS this
    build of sipsimple.core does not accept."""
    optional = {name: kwargs.pop(name) for name in OPTIONAL_KWARGS if name in kwargs}
    while True:
        call_kwargs = dict(kwargs)
        call_kwargs.update({name: value for name, value in optional.items()
                            if value is not None and name not in _unsupported_kwargs})
        try:
            return method(*args, **call_kwargs)
        except TypeError as e:
            rejected = [name for name in optional
                        if name not in _unsupported_kwargs and name in str(e)]
            if not rejected:
                raise
            for name in rejected:
                _unsupported_kwargs.add(name)
                log.warning('this build of sipsimple.core does not support %s: %s',
                            name, OPTIONAL_KWARGS[name])


# Headers that belong to the dialog or to the hop and must never be copied
# from one leg to the other.  Everything else (P-Asserted-Identity,
# Diversion, Privacy, Subject, Alert-Info, History-Info, X-*, ...) is
# relayed as-is.
NON_RELAYED_HEADERS = {
    'accept', 'accept-encoding', 'accept-language', 'allow', 'allow-events',
    'authentication-info', 'authorization', 'call-id', 'contact',
    'content-disposition', 'content-encoding', 'content-language',
    'content-length', 'content-type', 'cseq', 'date', 'expires', 'from',
    'max-forwards', 'min-expires', 'min-se', 'path', 'proxy-authenticate',
    'proxy-authorization', 'proxy-require', 'rack', 'reason', 'record-route',
    'refer-to', 'referred-by', 'replaces', 'require', 'route', 'rseq',
    'session-expires', 'supported', 'timestamp', 'to',
    'unsupported', 'via', 'warning', 'www-authenticate',
}
# User-Agent and Server are deliberately NOT in the list above: the peer's
# identity is carried across so the callee sees the caller's User-Agent and the
# caller sees the callee's Server. The engine's own _cb_add_user_agent_hdr /
# _cb_add_server_hdr only add theirs when the header is absent, so a relayed one
# wins and there is no duplicate. Messages the B2BUA generates itself (a 488, a
# 500, a locally built 100) carry the engine's string, as they should.

LOOP_DETECTION_HEADER = 'X-B2BUA'

# Credentials sent by the caller, relayed onto the outbound INVITE.
CREDENTIAL_HEADERS = ('Authorization', 'Proxy-Authorization')
# Challenges received on the outbound leg, relayed back to the caller.
CHALLENGE_HEADERS = ('WWW-Authenticate', 'Proxy-Authenticate')


def pick_headers(headers, names):
    """Extract the given headers from a received message as Header objects.

    Reading Authorization / Proxy-Authenticate & co needs a sipsimple.core that
    exposes them: the stock _pjsip_msg_to_dict() drops all four, since pjsip
    parses them into dedicated structures rather than generic string headers."""
    result = []
    for name in names:
        value = headers.get(name, None)
        body = getattr(value, 'body', None)
        if body:
            result.append(Header(name, body if isinstance(body, str) else body.decode()))
    return result


def relay_headers(headers, marker=None, exclude=NON_RELAYED_HEADERS):
    """Turn the header dict of a received message into a list of Header
    objects usable as extra_headers on the other leg."""
    result = []
    for name, value in headers.items():
        if name.lower() in exclude:
            continue
        if isinstance(value, (list, int)):
            # multi-value headers (Contact/Via/Record-Route) and Content-Length
            continue
        body = getattr(value, 'body', None)
        if body is None:
            continue
        result.append(Header(name, body if isinstance(body, str) else body.decode()))
    if marker is not None:
        result.append(Header(LOOP_DETECTION_HEADER, marker))
    return result


CALL_ID_RE = re.compile(rb'^(?:Call-ID|i)[ \t]*:[ \t]*(.+?)[ \t\r]*$',
                        re.IGNORECASE | re.MULTILINE)


def message_call_id(packet):
    """Pull the Call-ID out of a raw SIP message, so a trace line can be
    attributed to one of the two legs."""
    match = CALL_ID_RE.search(packet)
    return match.group(1).decode(errors='replace') if match else None


def sdp_direction(raw):
    """Summarise what an SDP says about media direction, so hold and unhold are
    readable in the log without turning on a full SIP trace."""
    if raw is None:
        return 'no sdp'
    text = raw.decode(errors='replace').lower()
    if 'c=in ip4 0.0.0.0' in text:
        return 'held, c=0.0.0.0'
    for attribute in ('inactive', 'sendonly', 'recvonly', 'sendrecv'):
        if 'a=%s' % attribute in text:
            return attribute
    return 'sendrecv implied'


def sdp_body(data):
    """Return the raw SDP bytes carried by a received message, or None."""
    body = getattr(data, 'body', None)
    if not body:
        return None
    content_type = data.headers.get('Content-Type', None)
    if content_type is not None and content_type.content_type.lower() != 'application/sdp':
        return None
    return body if isinstance(body, bytes) else body.encode()


class CallLeg(object):
    """Bookkeeping for one side of a B2BUA call."""

    def __init__(self, invitation=None):
        self.invitation = invitation
        self.answered = False

    @property
    def gone(self):
        return self.invitation is None or self.invitation.state in (None, 'disconnected')


@implementer(IObserver)
class B2BUACall(object):
    """One inbound dialog glued to one outbound dialog."""

    _count = 0

    def __init__(self, b2bua, invitation, data):
        B2BUACall._count += 1
        self.id = B2BUACall._count
        self.b2bua = b2bua
        self.lock = RLock()
        self.inbound = CallLeg(invitation)
        self.outbound = None
        self.ended = False
        self.finished = False
        self.traced_call_ids = []
        # Minted here, not left to pjsip: the outgoing Call-ID is then known from
        # the first log line of the call rather than only once the INVITE has
        # been built, and it stays the same for the life of the leg. pjsip's own
        # look like this, so keep the shape.
        self.outbound_call_id = str(uuid.uuid4()).upper()

        self.request_uri = invitation.request_uri
        self.from_header = invitation.from_header
        self.to_header = invitation.to_header
        self.offer = sdp_body(data)
        self.relayed_headers = self._relay_headers(data.headers, marker=b2bua.instance_id,
                                                   outbound=True)
        # Credentials the caller already computed for this Request-URI. The
        # digest covers method + digest-uri + nonce, all of which the outbound
        # leg reproduces unchanged, so the proxy accepts them as-is.
        self.credential_headers = pick_headers(data.headers, CREDENTIAL_HEADERS) \
            if b2bua.options.relay_auth else []

        self.notification_center = NotificationCenter()
        self.notification_center.add_observer(self, sender=invitation)
        self.b2bua.register_leg(invitation.call_id, 'inbound', self)

    def __repr__(self):
        return '<B2BUACall %d>' % self.id

    @staticmethod
    def _call_id(leg):
        """The Call-ID of a leg, or why there isn't one yet.

        <none>    the leg does not exist: for the outbound leg, before the DNS
                  lookup has come back, and for good if the call is rejected
                  before an outbound leg is ever placed
        <pending> the Invitation exists but has no dialog yet, so pjsip has not
                  generated its Call-ID: only until send_invite() returns
        """
        if leg is None or leg.invitation is None:
            return '<none>'
        return leg.invitation.call_id or '<pending>'

    @property
    def tag(self):
        """Log prefix: the call number and the Call-ID of both legs, so a log
        line can always be tied to both sides of a trace."""
        outbound = self._call_id(self.outbound)
        if outbound in ('<none>', '<pending>'):
            # not placed yet, but we already know what it will be
            outbound = self.outbound_call_id
        return '[call %d in=%s out=%s]' % (self.id, self._call_id(self.inbound), outbound)

    def _log(self, message, *args):
        log.info(self.tag + ' ' + message, *args)

    def _relay_headers(self, headers, marker=None, outbound=False):
        """Headers to carry onto the other leg. --user-agent applies to the
        outgoing leg only: there the peer's User-Agent is dropped and replaced,
        while responses going back to the caller still carry the callee's
        Server header."""
        override = self.b2bua.options.user_agent if outbound else None
        exclude = NON_RELAYED_HEADERS | {'user-agent'} if override else NON_RELAYED_HEADERS
        result = relay_headers(headers, marker=marker, exclude=exclude)
        if override:
            result.append(Header('User-Agent', override))
        return result

    # ------------------------------------------------------------------
    # inbound leg -> outbound leg
    # ------------------------------------------------------------------

    def start(self):
        invitation = self.inbound.invitation
        self._log('incoming INVITE from %s to %s', self.from_header.uri, self.request_uri)

        if self.offer is None:
            self._log('no SDP offer in the INVITE (delayed offer is not supported), rejecting')
            self._reject_inbound(488, 'Not Acceptable Here')
            return

        try:
            invitation.send_response(100)
        except (SIPCoreError, PJSIPError) as e:
            self._log('could not send 100 Trying: %s', e)

        self._place_outbound_leg()

    @run_in_green_thread
    def _place_outbound_leg(self):
        target = self.request_uri
        uri = SIPURI(host=target.host, port=target.port, secure=target.secure,
                     parameters=dict(target.parameters))
        try:
            routes = DNSLookup().lookup_sip_proxy(uri, self.b2bua.supported_transports).wait()
        except DNSLookupError as e:
            self._log('DNS lookup for %s failed: %s', target.host, e)
            self._fail(478, 'Unresolvable Destination')
            return
        if not routes:
            self._log('DNS lookup for %s returned no routes', target.host)
            self._fail(478, 'Unresolvable Destination')
            return
        self._send_outbound_invite(routes[0])

    @run_in_twisted_thread
    def _send_outbound_invite(self, route):
        with self.lock:
            if self.ended:
                return
            if self.inbound.invitation.state not in ('incoming', 'early'):
                self._log('the caller went away before the outbound leg could be placed')
                self.end()
                self._check_finished()
                return

            self._log('placing the outbound leg via %s', route)
            invitation = Invitation()
            self.outbound = CallLeg(invitation)
            self.notification_center.add_observer(self, sender=invitation)

            try:
                sdp = SDPSession.parse(self.offer)
            except SIPCoreError as e:
                self._log('cannot parse the offer received from the caller: %s', e)
                self._fail(488, 'Not Acceptable Here')
                return

            extra_headers = list(self.relayed_headers) + list(self.credential_headers)
            if self.credential_headers:
                self._log('relaying the caller\'s credentials on the outbound leg')

            try:
                send(invitation.send_invite,
                     SIPURI.new(self.request_uri),
                     FromHeader(SIPURI.new(self.from_header.uri), self.from_header.display_name),
                     ToHeader(SIPURI.new(self.to_header.uri), self.to_header.display_name),
                     RouteHeader(route.uri),
                     ContactHeader(self.b2bua.contact_factory[route]),
                     sdp,
                     extra_headers=extra_headers,
                     raw_sdp=self.offer,
                     call_id=self.outbound_call_id)
            except (SIPCoreError, PJSIPError) as e:
                self._log('could not send the outbound INVITE: %s', e)
                self._fail(500, 'Internal Server Error')
                return
            self.b2bua.register_leg(invitation.call_id, 'outbound', self)
            self._log('outbound INVITE sent')

    # ------------------------------------------------------------------
    # outbound leg -> inbound leg
    # ------------------------------------------------------------------

    def _relay_provisional(self, data):
        code = data.code
        if code == 100:
            return
        raw = sdp_body(data)
        sdp = None
        if raw is not None and not self.inbound.answered:
            try:
                sdp = SDPSession.parse(raw)
            except SIPCoreError as e:
                self._log('cannot parse the early answer, relaying the response without SDP: %s', e)
                sdp = raw = None
        else:
            raw = None
        try:
            send(self.inbound.invitation.send_response, code, data.reason, sdp=sdp,
                 extra_headers=self._relay_headers(data.headers), raw_sdp=raw)
        except (SIPCoreError, PJSIPError) as e:
            self._log('could not relay the %s response to the caller: %s', code, e)
            return
        if sdp is not None:
            self.inbound.answered = True
        self._log('relayed %s %s to the caller%s', code, data.reason,
                  ' with early media' if sdp is not None else '')

    def _relay_final(self, data):
        raw = sdp_body(data)
        sdp = None
        if not self.inbound.answered:
            if raw is None:
                self._log('the callee answered without SDP; cannot complete the caller leg')
                self._fail(488, 'Not Acceptable Here')
                self.end()
                return
            try:
                sdp = SDPSession.parse(raw)
            except SIPCoreError as e:
                self._log('cannot parse the answer received from the callee: %s', e)
                self._fail(488, 'Not Acceptable Here')
                self.end()
                return
        else:
            # offer/answer already completed in a reliable 18x
            raw = None
        try:
            send(self.inbound.invitation.send_response, 200, data.reason, sdp=sdp,
                 extra_headers=self._relay_headers(data.headers), raw_sdp=raw)
        except (SIPCoreError, PJSIPError) as e:
            # This is where pjsip's SDP negotiator refuses the relayed answer
            # as a valid answer to the relayed offer.
            self._log('could not answer the caller with the relayed SDP: %s', e)
            self._fail(488, 'Not Acceptable Here')
            self.end()
            return
        self.inbound.answered = True
        self.outbound.answered = True
        self._log('relayed 200 %s to the caller (%s), call established',
                  data.reason or '', sdp_direction(raw) if raw is not None else
                  'answer already sent in a reliable 18x')

    # ------------------------------------------------------------------
    # re-INVITE relaying (hold, codec change, ...)
    # ------------------------------------------------------------------

    def _direction(self, source):
        return 'caller -> callee' if source is self.inbound else 'callee -> caller'

    def _peer(self, leg):
        return 'caller' if leg is self.inbound else 'callee'

    def _leg_ended(self, leg, data):
        """Why a leg finished. "disconnected" is the wrong word for a leg that
        was never connected in the first place: a call we answered with a 407 so
        the caller can authenticate was answered, not disconnected."""
        peer = self._peer(leg)
        code = getattr(data, 'code', 0) or 0
        reason = (getattr(data, 'reason', '') or '').strip()
        status = ('%s %s' % (code, reason)).strip()
        originator = getattr(data, 'originator', None)
        detail = getattr(data, 'disconnect_reason', None)
        if leg.answered:
            if originator == 'remote':
                return '%s leg closed: the %s hung up' % (peer, peer)
            return '%s leg closed: %s' % (peer, detail or 'ended locally')
        if code >= 300:
            if originator == 'local':
                return '%s leg closed: we answered %s' % (peer, status)
            return '%s leg closed: answered %s' % (peer, status)
        if originator == 'remote':
            return '%s leg closed: cancelled before it was answered' % peer
        return '%s leg closed: %s' % (peer, detail or 'ended before it was answered')

    def _relay_reinvite(self, source, target, data):
        raw = sdp_body(data)
        if raw is None:
            self._log('re-INVITE from the %s has no SDP, rejecting it with 488',
                      self._peer(source))
            self._respond(source, 488, 'Not Acceptable Here')
            return
        if target is None or target.gone or target.invitation.state != 'connected' \
                or target.invitation.sub_state != 'normal':
            self._log('re-INVITE from the %s arrived while the other leg is busy, '
                      'rejecting it with 491', self._peer(source))
            self._respond(source, 491, 'Request Pending')
            return
        try:
            send(target.invitation.send_reinvite, sdp=SDPSession.parse(raw),
                 extra_headers=self._relay_headers(data.headers,
                                                   outbound=target is self.outbound),
                 raw_sdp=raw)
        except (SIPCoreError, PJSIPError) as e:
            self._log('could not relay the re-INVITE %s: %s', self._direction(source), e)
            self._respond(source, 500, 'Internal Server Error')
            return
        self._log('relayed a re-INVITE %s (%s)', self._direction(source), sdp_direction(raw))

    def _relay_reinvite_response(self, source, target, data):
        code = getattr(data, 'code', None) or 408
        reason = getattr(data, 'reason', None)
        if target is None or target.gone:
            self._log('the %s answered the re-INVITE with %s %s but the other leg is '
                      'already gone', self._peer(source), code, reason or '')
            return
        if code // 100 != 2:
            self._respond(target, code, reason,
                          extra_headers=self._relay_headers(data.headers))
            self._log('relayed %s %s of the re-INVITE to the %s', code, reason or '',
                      self._peer(target))
            return
        raw = sdp_body(data)
        sdp = None
        if raw is not None:
            try:
                sdp = SDPSession.parse(raw)
            except SIPCoreError as e:
                self._log('cannot parse the SDP of the re-INVITE response: %s', e)
                raw = None
        try:
            send(target.invitation.send_response, 200, reason, sdp=sdp,
                 extra_headers=self._relay_headers(data.headers,
                                                   outbound=target is self.outbound),
                 raw_sdp=raw)
        except (SIPCoreError, PJSIPError) as e:
            self._log('could not relay the 200 OK of the re-INVITE to the %s: %s',
                      self._peer(target), e)
            return
        self._log('relayed 200 %s of the re-INVITE to the %s (%s)', reason or '',
                  self._peer(target), sdp_direction(raw))

    # ------------------------------------------------------------------
    # teardown
    # ------------------------------------------------------------------

    def _respond(self, leg, code, reason=None, extra_headers=None):
        if leg is None or leg.gone:
            return
        try:
            leg.invitation.send_response(code, reason, extra_headers=extra_headers or [])
        except (SIPCoreError, PJSIPError) as e:
            self._log('could not send a %s response: %s', code, e)

    def _reject_inbound(self, code, reason=None, extra_headers=None):
        if self.inbound.gone or self.inbound.invitation.state not in ('incoming', 'early'):
            return
        self._respond(self.inbound, code, reason, extra_headers)

    def _fail(self, code, reason=None):
        """Reject the caller and make sure the outbound leg is torn down."""
        self._reject_inbound(code, reason)
        with self.lock:
            self.ended = True
        if self.outbound is not None and not self.outbound.gone:
            try:
                self.outbound.invitation.end()
            except (SIPCoreError, PJSIPError):
                pass
        self._check_finished()

    def end(self):
        with self.lock:
            if self.ended:
                return
            self.ended = True
        for leg in (self.inbound, self.outbound):
            if leg is None or leg.gone:
                continue
            try:
                if leg is self.inbound and leg.invitation.state in ('incoming', 'early'):
                    leg.invitation.send_response(486, 'Busy Here')
                else:
                    leg.invitation.end()
            except (SIPCoreError, PJSIPError) as e:
                self._log('could not tear down a leg: %s', e)

    def _check_finished(self):
        if self.finished:
            return
        for leg in (self.inbound, self.outbound):
            if leg is not None and not leg.gone:
                return
        if self.outbound is None and not self.ended and not self.inbound.gone:
            return
        self.finished = True
        for leg in (self.inbound, self.outbound):
            if leg is not None and leg.invitation is not None:
                self.notification_center.discard_observer(self, sender=leg.invitation)
        self.b2bua.remove_call(self)

    # ------------------------------------------------------------------
    # notification handling -- everything runs in the reactor thread
    # ------------------------------------------------------------------

    @run_in_twisted_thread
    def handle_notification(self, notification):
        handler = getattr(self, '_NH_%s' % notification.name, Null)
        handler(notification)

    def _NH_SIPInvitationChangedState(self, notification):
        invitation = notification.sender
        data = notification.data
        state = data.state
        sub_state = getattr(data, 'sub_state', None)
        prev_sub_state = getattr(data, 'prev_sub_state', None)

        if self.outbound is not None and invitation is self.outbound.invitation:
            if state == 'early' and getattr(data, 'code', None):
                self._relay_provisional(data)
            elif state == 'connecting' and (getattr(data, 'code', 0) or 0) // 100 == 2:
                self._relay_final(data)
            elif state == 'connected' and sub_state == 'received_proposal':
                self._relay_reinvite(self.outbound, self.inbound, data)
            elif state == 'connected' and prev_sub_state == 'sent_proposal' and sub_state == 'normal':
                self._relay_reinvite_response(self.outbound, self.inbound, data)
            elif state == 'disconnected':
                code = getattr(data, 'code', 0) or 0
                self._log('%s', self._leg_ended(self.outbound, data))
                if not self.inbound.answered and 300 <= code < 700:
                    # relay the failure verbatim to the caller, including any
                    # authentication challenge, so the caller can answer it and
                    # retry -- the retry arrives as a fresh INVITE and its
                    # credentials are relayed onto the new outbound leg
                    extra_headers = self._relay_headers(data.headers)
                    if code in (401, 407) and self.b2bua.options.relay_auth:
                        extra_headers += pick_headers(data.headers, CHALLENGE_HEADERS)
                        if pick_headers(data.headers, CHALLENGE_HEADERS):
                            self._log('relaying the %s challenge to the caller', code)
                        else:
                            self._log('got a %s but no challenge header was available; '
                                      'is sipsimple.core patched to expose them?', code)
                    self._reject_inbound(code, getattr(data, 'reason', None) or None,
                                         extra_headers=extra_headers)
                    with self.lock:
                        self.ended = True
                else:
                    self.end()
        elif invitation is self.inbound.invitation:
            if state == 'connected' and sub_state == 'received_proposal':
                self._relay_reinvite(self.inbound, self.outbound, data)
            elif state == 'connected' and prev_sub_state == 'sent_proposal' and sub_state == 'normal':
                self._relay_reinvite_response(self.inbound, self.outbound, data)
            elif state == 'disconnected':
                self._log('%s', self._leg_ended(self.inbound, data))
                self.end()
        else:
            return

        self._check_finished()


@implementer(IObserver)
class B2BUA(object):

    def __init__(self, options):
        self.options = options
        self.calls = set()
        self.lock = RLock()
        self.engine = Engine()
        self.contact_factory = ContactURIFactory(username='b2bua')
        self.instance_id = 'sip-b2bua-%08x' % (id(self) & 0xffffffff)
        self.stopped = Event()
        self.thread = None
        # Call-ID -> (leg name, call), for per-leg SIP tracing. A message is
        # traced at the transport layer, before the Invitation that will own it
        # exists, so traces for an unknown Call-ID are held briefly and flushed
        # when the leg registers itself.
        self.trace_legs = {}
        self.pending_traces = deque(maxlen=64)

    @property
    def tracing(self):
        return bool(self.options.trace_sip or self.options.trace_inbound
                    or self.options.trace_outbound)

    def traced(self, leg):
        if self.options.trace_sip:
            return True
        return getattr(self.options, 'trace_%s' % leg, False)

    def register_leg(self, call_id, leg, call):
        if not call_id or self.options.trace_sip or not self.tracing:
            return
        self.trace_legs[call_id] = (leg, call)
        call.traced_call_ids.append(call_id)
        for entry in [e for e in self.pending_traces if e[0] == call_id]:
            self.pending_traces.remove(entry)
            self._emit_trace(leg, call, entry[1])

    def unregister_call(self, call):
        for call_id in call.traced_call_ids:
            self.trace_legs.pop(call_id, None)

    def _emit_trace(self, leg, call, line):
        if not self.traced(leg):
            return
        log.debug('%s %s %s', call.tag if call is not None else '', leg.upper(), line)

    @property
    def supported_transports(self):
        transports = []
        for transport in ('udp', 'tcp', 'tls'):
            try:
                if getattr(self.engine, '%s_port' % transport, None):
                    transports.append(transport)
            except AttributeError:
                pass
        return transports

    # -- lifecycle ------------------------------------------------------

    def start(self):
        ThreadManager().start()
        self.thread = Thread(name='Reactor Thread', target=self._run_reactor)
        self.thread.start()

    def _run_reactor(self):
        # make the twisted reactor green so that eventlib -- and with it the
        # SDK's DNS lookups -- can run on it
        from eventlib.twistedutil import join_reactor; del join_reactor

        notification_center = NotificationCenter()
        notification_center.add_observer(self, name='SIPInvitationChangedState')
        notification_center.add_observer(self, name='SIPEngineDidStart')
        notification_center.add_observer(self, name='SIPEngineDidFail')
        if self.tracing:
            notification_center.add_observer(self, name='SIPEngineSIPTrace')

        # The engine's user_agent is deliberately left at its default: it applies
        # to every message on both legs, which is not what --user-agent means.
        # That option is applied per-message on the outgoing leg only.
        self.engine.start(udp_port=self.options.udp_port,
                          tcp_port=self.options.tcp_port,
                          tls_port=self.options.tls_port,
                          ip_address=self.options.ip_address,
                          trace_sip=self.tracing,
                          log_level=self.options.log_level)
        # the subsystems are started from the SIPEngineDidStart handler: the
        # engine builds its PJSIPUA on its own thread and none of its
        # attributes exist before that
        reactor.run(installSignalHandlers=False)
        self.stopped.set()

    @run_in_green_thread
    def _start_subsystems(self):
        DNSManager().start()
        log.info('B2BUA listening on %s (udp=%s tcp=%s tls=%s)',
                 getattr(self.engine, 'ip_address', None) or '0.0.0.0',
                 getattr(self.engine, 'udp_port', None),
                 getattr(self.engine, 'tcp_port', None),
                 getattr(self.engine, 'tls_port', None))

    def stop(self):
        log.info('shutting down')
        with self.lock:
            calls = list(self.calls)
        for call in calls:
            call.end()
        reactor.callFromThread(self._stop_reactor)
        self.stopped.wait(5)
        self.engine.stop()
        ThreadManager().stop()

    def _stop_reactor(self):
        DNSManager().stop()
        reactor.stop()

    # -- call table -----------------------------------------------------

    def remove_call(self, call):
        with self.lock:
            self.calls.discard(call)
            active = len(self.calls)
        log.info('%s finished, %d call(s) active', call.tag, active)
        self.unregister_call(call)

    # -- notifications --------------------------------------------------

    @run_in_twisted_thread
    def handle_notification(self, notification):
        handler = getattr(self, '_NH_%s' % notification.name, Null)
        handler(notification)

    def _NH_SIPInvitationChangedState(self, notification):
        data = notification.data
        if data.state != 'incoming':
            return
        invitation = notification.sender

        marker = data.headers.get(LOOP_DETECTION_HEADER, None)
        if marker is not None and getattr(marker, 'body', None) == self.instance_id:
            log.warning('rejecting a looped INVITE (Call-ID %s)', invitation.call_id)
            try:
                invitation.send_response(482, 'Loop Detected')
            except (SIPCoreError, PJSIPError):
                pass
            return

        with self.lock:
            active = len(self.calls)
        if self.options.max_calls and active >= self.options.max_calls:
            try:
                invitation.send_response(503, 'Maximum Number of Calls Reached')
            except (SIPCoreError, PJSIPError):
                pass
            return

        call = B2BUACall(self, invitation, data)
        with self.lock:
            self.calls.add(call)
        call.start()

    def _NH_SIPEngineDidStart(self, notification):
        self._start_subsystems()

    def _NH_SIPEngineDidFail(self, notification):
        log.error('the SIP engine failed, exiting')
        reactor.callFromThread(self._stop_reactor)

    def _NH_SIPEngineSIPTrace(self, notification):
        data = notification.data
        line = '%s %s:%s %s %s:%s (%s)\n%s' % (
            'RECEIVED' if data.received else 'SENDING',
            data.source_ip, data.source_port,
            '<--' if data.received else '-->',
            data.destination_ip, data.destination_port, data.transport,
            data.data.decode(errors='replace'))
        if self.options.trace_sip:
            log.debug('%s', line)
            return
        call_id = message_call_id(data.data)
        try:
            leg, call = self.trace_legs[call_id]
        except KeyError:
            # not yet attributable to a leg -- hold it until one claims it
            self.pending_traces.append((call_id, line))
            return
        self._emit_trace(leg, call, line)


def main():
    parser = ArgumentParser(description='Signalling-only SIP back-to-back user agent')
    parser.add_argument('--ip-address', default=None,
                        help='local IP address to bind to (default: all interfaces)')
    parser.add_argument('--udp-port', type=int, default=5080, help='UDP port, 0 disables (default: 5080)')
    parser.add_argument('--tcp-port', type=int, default=None, help='TCP port (default: disabled)')
    parser.add_argument('--tls-port', type=int, default=None, help='TLS port (default: disabled)')
    parser.add_argument('--user-agent', default=None,
                        help='User-Agent to put on the outgoing leg, replacing the caller\'s '
                             '(default: relay the caller\'s unchanged)')
    parser.add_argument('--max-calls', type=int, default=0,
                        help='maximum number of concurrent calls (default: unlimited)')
    parser.add_argument('--no-auth-relay', action='store_false', dest='relay_auth', default=True,
                        help='do not relay authentication challenges and credentials between the legs')
    parser.add_argument('--trace-sip', action='store_true',
                        help='log every SIP message, on both legs and unattributed ones')
    parser.add_argument('--trace-inbound', action='store_true',
                        help='log only the SIP messages of the caller leg')
    parser.add_argument('--trace-outbound', action='store_true',
                        help='log only the SIP messages of the callee leg')
    parser.add_argument('--log-level', type=int, default=0, help='pjsip log level, 0-5 (default: 0)')
    parser.add_argument('-v', '--verbose', action='store_true', help='enable debug logging')
    options = parser.parse_args()

    tracing = options.trace_sip or options.trace_inbound or options.trace_outbound
    level = logging.DEBUG if (options.verbose or tracing) else logging.INFO
    logging.basicConfig(level=level, format='%(asctime)s %(levelname)-7s %(message)s')
    # python-application installs a root handler when sipsimple is imported,
    # which makes basicConfig() above a no-op and leaves the level at INFO --
    # force it on the root logger and on every handler it already has.
    root = logging.getLogger()
    root.setLevel(level)
    for handler in root.handlers:
        handler.setLevel(level)
    log.setLevel(level)

    b2bua = B2BUA(options)

    def terminate(signum, frame):
        b2bua.stop()

    signal.signal(signal.SIGINT, terminate)
    signal.signal(signal.SIGTERM, terminate)

    b2bua.start()
    while not b2bua.stopped.wait(1):
        pass
    return 0


if __name__ == '__main__':
    sys.exit(main())
