#!/usr/bin/env python3

"""
sip-b2bua.py -- a signalling-only Back-to-Back User Agent built on the
SIP SIMPLE SDK.

For every incoming INVITE the B2BUA creates a second dialog towards the
destination in the Request-URI.  It is a new dialog, not a new call:
what differs between the two legs is only what identifies the dialog or
the hop -- Call-ID, From tag, To tag, CSeq space, Contact, Via, Route,
Max-Forwards, User-Agent.  Everything else is carried across unchanged:
the Request-URI, the From and To URIs and display names, and every
header that is not dialog- or hop-specific (see NON_RELAYED_HEADERS for
the exclusion list; anything not listed there is relayed verbatim, in
both directions, requests and responses alike).

The SDP is relayed too, byte for byte: the offer from the inbound leg
goes out in the outbound INVITE, and the answer from the outbound leg
goes back to the caller.  Media therefore flows directly between the two
endpoints -- the B2BUA never touches RTP and needs no media transports,
no codecs and no sound device.

Byte-exact SDP relaying needs the `raw_sdp` keyword argument that was
added to Invitation.send_invite() / send_response() / send_reinvite() in
sipsimple.core.  Without it pjsip regenerates the body from its own SDP
negotiator (codec intersection, payload type renumbering, attribute
pruning), which is not acceptable for a B2BUA that is not in the media
path.  The script detects at runtime whether the SDK supports `raw_sdp`
and warns loudly when it has to fall back to the regenerated body.

Routing: the outbound leg does its own RFC 3263 lookup (NAPTR -> SRV ->
A) on the Request-URI of the incoming INVITE.  No outbound proxy and no
registration.

Authentication is relayed: a 401/407 on the outbound leg goes back to
the caller together with its challenge, and the credentials the caller
then supplies are relayed onto the new outbound INVITE.  The digest
stays valid because the method and the Request-URI are preserved end to
end.  See docs/sip-b2bua.txt.

Usage:
    ./sip-b2bua.py --udp-port 5080 --trace-sip
"""

